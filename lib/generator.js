const phraseRules = [
  [/(достало|надоело|сил больше нет|невозможно терпеть)/gi, "Ситуация вызывает обеспокоенность и требует рассмотрения"],
  [/(ничего не делают|никто ничего не делает)/gi, "на момент подготовки обращения проблема не устранена"],
  [/(забили на нас|игнорят)/gi, "ответ на ранее направленное сообщение не получен"],
  [/(разберитесь уже)/gi, "прошу проверить обстоятельства и сообщить о принятых мерах"],
  [/(кошмар|ужас|полный бардак)/gi, "ситуация вызывает обеспокоенность"]
];

export function cleanText(value = "") {
  return String(value).trim().replace(/\s+/g, " ").replace(/[!?]{2,}/g, ".").replace(/[.]{2,}/g, ".");
}

export function formalize(value) {
  let text = cleanText(value);
  for (const [pattern, replacement] of phraseRules) {
    text = text.replace(pattern, replacement);
  }
  text = text.replace(/^(короче[,:]?\s*|в общем[,:]?\s*|ну вот[,:]?\s*)/i, "");
  return text.replace(/\s+([,.!?])/g, "$1").trim();
}

export function buildLocalResult(data) {
  const info = categoryData[data.category] || categoryData.other;
  const recipient = cleanText(data.recipient) || info.recipient;
  const cityLine = cleanText(data.city) ? "Населённый пункт: " + cleanText(data.city) : "";
  const timeLine = cleanText(data.since) ? "Дата или период: " + cleanText(data.since) : "";
  const desiredLine = cleanText(data.desired) ? "Желаемый результат: " + cleanText(data.desired) : "";
  const previousLine = cleanText(data.previousContact) ? "Ранее предпринятые действия: " + cleanText(data.previousContact) : "";
  const evidenceLine = cleanText(data.evidence) ? "Имеющиеся подтверждения: " + cleanText(data.evidence) : "";
  const narrative = formalize(data.description);
  const targeted = issueSpecificPlan(data.category, data.description);
  const plans = targeted ? [targeted, ...info.plans.slice(0, 3)] : info.plans;
  const document = [
    "Адресат: " + recipient,
    "От: [ФИО заявителя]",
    cityLine,
    "Контакт для ответа: [указать удобный способ связи]",
    "",
    "ОБРАЩЕНИЕ",
    info.subject,
    "",
    "Прошу рассмотреть следующую ситуацию.",
    "",
    "Суть обращения",
    narrative ? (narrative.charAt(0).toLocaleUpperCase("ru-RU") + narrative.slice(1)) + (/[.!?]$/.test(narrative) ? "" : ".") : "[Подробно опишите ситуацию]",
    timeLine,
    desiredLine,
    previousLine,
    evidenceLine,
    "",
    "В связи с изложенным прошу:",
    ...info.ask.map((item, index) => (index + 1) + ". " + item),
    "",
    "При наличии прошу учесть приложенные материалы, подтверждающие изложенные обстоятельства.",
    "Ответ прошу направить способом, указанным в контактных данных.",
    "",
    "Приложения: [перечислить документы, фотографии или иные материалы при наличии].",
    "",
    "Дата: [дата подачи]",
    "Подпись: [ФИО]"
  ].filter((line, index, list) => line !== "" || (index > 0 && list[index - 1] !== "")).join("\n");

  const review_notes = [];
  if (!cleanText(data.recipient)) review_notes.push("Уточните точное название организации или должность адресата.");
  if (!cleanText(data.city)) review_notes.push("При необходимости добавьте населённый пункт и точное место события.");
  if (!cleanText(data.since)) review_notes.push("Уточните дату или период, чтобы адресату было проще проверить обстоятельства.");
  if (!cleanText(data.evidence)) review_notes.push("Перечислите только реально имеющиеся доказательства и приложите копии при необходимости.");
  review_notes.push("Проверьте, что все факты изложены точно и не содержат предположений.");
  review_notes.push("Замените поля в квадратных скобках и проверьте документ перед отправкой.");

  return {
    document,
    plan: plans.map(([title, description]) => ({ title, description })),
    review_notes: review_notes.slice(0, 6)
  };
}

