function cleanText(value = "") {
  return String(value).trim().replace(/\s+/g, " ").replace(/[!?]{2,}/g, ".").replace(/[.]{2,}/g, ".");
}

function capitalize(value) {
  const text = cleanText(value);
  return text ? text.charAt(0).toLocaleUpperCase("ru-RU") + text.slice(1) : "";
}

function extractRequestedOutcome(value) {
  const source = cleanText(value);
  const patterns = [
    /(?:хочу|хотелось бы|мне нужно|мне необходимо|прошу)\s*,?\s*(?:чтобы\s+)?(.+?)(?:[.!?]|$)/i,
    /(?:разберитесь|устраните|исправьте|верните|замените|примите меры)\s+(?:уже\s+)?(.+?)(?:[.!?]|$)/i
  ];

  for (const pattern of patterns) {
    const match = source.match(pattern);
    if (match?.[1]) return formalizeDesired(match[1]);
  }
  return "";
}

function formalizeDesired(value) {
  let action = cleanText(value)
    .replace(/^(?:наконец|уже|пожалуйста)\s+/i, "")
    .replace(/[.!?]+$/g, "");

  if (!action) return "";
  if (/^(?:с|по поводу)\s+/i.test(action)) {
    const subject = action.replace(/^с\\s+/i, "");
    return capitalize("проверить обстоятельства, связанные с " + subject + ", и сообщить о принятых мерах");
  }
  if (/разобра(ться|лись|ться бы)/i.test(action)) {
    const subject = action.replace(/.*?разобра(?:ться|лись|ться бы)\s*/i, "").replace(/^с\s+/i, "");
    return capitalize("проверить обстоятельства, связанные с " + subject + ", и сообщить о принятых мерах");
  }

  action = action
    .replace(/вернули\s+(?:мне\s+)?деньги/gi, "рассмотреть вопрос о возврате денежных средств")
    .replace(/вернуть\s+(?:мне\s+)?деньги/gi, "рассмотреть вопрос о возврате денежных средств")
    .replace(/починили|починить/gi, "устранить неисправность")
    .replace(/проверили/gi, "проверить")
    .replace(/объяснили/gi, "предоставить разъяснения")
    .replace(/рассказали/gi, "предоставить информацию")
    .replace(/решили вопрос/gi, "урегулировать вопрос")
    .replace(/устранили/gi, "устранить")
    .replace(/восстановили/gi, "восстановить")
    .replace(/сделали/gi, "выполнить необходимые действия")
    .replace(/приняли меры/gi, "принять необходимые меры")
    .replace(/как решить вопрос/gi, "о возможных способах урегулирования ситуации")
    .replace(/наконец/gi, "")
    .replace(/\s+/g, " ")
    .trim();

  return capitalize(action);
}

function rewriteClause(value, category, fullSource) {
  let text = cleanText(value)
    .replace(/^(?:ну|короче|в общем)[,:]?\s*/i, "")
    .replace(/^(?:это\s+)?(?:достало|надоело|кошмар|ужас|полный бардак|сил больше нет|невозможно терпеть)[.!?]*/i, "")
    .replace(/(?:,\s*)?(?:достало|надоело|кошмар|ужас|полный бардак|сил больше нет|невозможно терпеть)[.!?]*/gi, "")
    .replace(/разберитесь уже|разберитесь/gi, "")
    .replace(/ничего не (?:делают|меняется)|никто ничего не делает/gi, "проблема до настоящего времени не устранена")
    .replace(/ничего не изменилось/gi, "проблема сохраняется")
    .replace(/игнорят|игнорируют/gi, "не предоставляют ответ")
    .replace(/мне сказали|сказали,?\s+что/gi, "мне сообщили, что")
    .replace(/ничем не могут помочь/gi, "не предложили способ решения вопроса")
    .replace(/не объясняют,?\s+что делать/gi, "не предоставляют разъяснений о дальнейших действиях")
    .replace(/не отвечает поддержка/gi, "ответ от службы поддержки не получен")
    .replace(/поддержка не отвечает/gi, "ответ от службы поддержки не получен");

  if (category === "housing") {
    text = text
      .replace(/еле т[её]пл(?:ые|ая|ый)/gi, "нагреваются недостаточно")
      .replace(/(?:дома|в квартире)\s+(?:очень\s+)?холодно/gi, "температура в помещении остаётся низкой")
      .replace(/нет отопления/gi, "отопление отсутствует")
      .replace(/нет горячей воды/gi, "горячее водоснабжение отсутствует")
      .replace(/вода еле теч[её]т/gi, "напор воды недостаточный");
  }

  if (category === "shop") {
    if (/наушник/i.test(fullSource)) {
      text = text.replace(/один перестал работать/gi, "один из наушников перестал функционировать");
    }
    text = text
      .replace(/в магазине отправляют в сервис/gi, "в магазине предлагают обратиться в сервисный центр")
      .replace(/бракованный/gi, "имеющий недостаток")
      .replace(/не работает/gi, "не функционирует")
      .replace(/сломался/gi, "вышел из строя");
  }

  if (category === "work") {
    text = text
      .replace(/зарплату задерживают/gi, "выплата заработной платы задерживается")
      .replace(/не платят зарплату/gi, "заработная плата не выплачивается")
      .replace(/начальник/gi, "руководитель")
      .replace(/не выплатили зарплату/gi, "заработная плата не выплачена");
  }

  if (category === "municipal") {
    text = text
      .replace(/большая яма на тротуаре/gi, "на тротуаре имеется значительное повреждение покрытия в виде ямы")
      .replace(/яма на дороге/gi, "на проезжей части имеется повреждение дорожного покрытия в виде ямы")
      .replace(/не убирают мусор/gi, "уборка мусора не осуществляется");
  }

  if (category === "delivery") {
    text = text
      .replace(/заказ не привезли|заказ не доставили/gi, "заказ не был доставлен")
      .replace(/курьер не приехал/gi, "курьер не прибыл")
      .replace(/заказ задержали/gi, "срок доставки заказа нарушен")
      .replace(/посылка не пришла/gi, "посылка не доставлена");
  }

  text = text
    .replace(/звонили\s+в\s+/gi, "обращались по телефону в ")
    .replace(/звонил\s+в\s+/gi, "обращался по телефону в ")
    .replace(/звонила\s+в\s+/gi, "обращалась по телефону в ")
    .replace(/писали\s+в\s+/gi, "направляли сообщение в ")
    .replace(/писал\s+в\s+/gi, "направлял сообщение в ")
    .replace(/писала\s+в\s+/gi, "направляла сообщение в ")
    .replace(/связывались с\s+/gi, "обращались к ")
    .replace(/в\s+магазине\s+сказали/gi, "при обращении в магазин сообщили")
    .replace(/\s+([,.!?])/g, "$1")
    .replace(/\s+/g, " ")
    .trim();

  return capitalize(text);
}

export function formalize(value, category = "other") {
  const source = cleanText(value);
  if (!source) return "";

  const clauses = source
    .split(/(?<=[.!?])\s+|\n+|;\s*/u)
    .map((part) => part.trim())
    .filter(Boolean);
  const rewritten = [];

  for (const clause of clauses) {
    const requestIndex = clause.search(/(?:хочу|хотелось бы|мне нужно|мне необходимо|прошу|разберитесь|устраните|исправьте|верните|замените)\s*/i);
    const factualPart = requestIndex > 0 ? clause.slice(0, requestIndex).trim() : clause;
    if (requestIndex === 0) continue;

    const fragments = factualPart.split(/,\s*(?:но|однако)\s+/i).map((part) => part.trim()).filter(Boolean);
    const formalFragments = fragments
      .map((part) => rewriteClause(part, category, source))
      .filter((part) => part && !/^(?:достало|надоело|кошмар|ужас|полный бардак)/i.test(part));

    if (formalFragments.length) rewritten.push(formalFragments.join(", однако "));
  }

  return rewritten.join(" ").replace(/\s+/g, " ").trim();
}

function shouldIncludeDetail(description, value) {
  const detail = cleanText(value).toLocaleLowerCase("ru-RU");
  const source = cleanText(description).toLocaleLowerCase("ru-RU");
  return Boolean(detail) && !source.includes(detail);
}

export function buildLocalResult(data) {
  const info = categoryData[data.category] || categoryData.other;
  const recipient = cleanText(data.recipient) || info.recipient;
  const source = cleanText(data.description);
  const inferredDesired = extractRequestedOutcome(source);
  const requestedResult = cleanText(data.desired) || inferredDesired;
  const cityLine = cleanText(data.city) ? "Населённый пункт: " + cleanText(data.city) : "";
  const timeLine = shouldIncludeDetail(source, data.since) ? "Дата или период: " + cleanText(data.since) : "";
  const desiredLine = requestedResult ? "Желаемый результат: " + cleanText(requestedResult) : "";
  const previousLine = shouldIncludeDetail(source, data.previousContact) ? "Ранее предпринятые действия: " + cleanText(data.previousContact) : "";
  const evidenceLine = shouldIncludeDetail(source, data.evidence) ? "Имеющиеся подтверждения: " + cleanText(data.evidence) : "";
  const narrative = formalize(source, data.category);
  const targeted = issueSpecificPlan(data.category, source);
  const plans = targeted ? [targeted, ...info.plans.slice(0, 3)] : info.plans;
  const narrativeBlock = narrative
    ? "Сообщаю о следующей ситуации.\n\n" + narrative + (/[.!?]$/.test(narrative) ? "" : ".")
    : "Обстоятельства ситуации требуют рассмотрения. Прошу учесть сведения, указанные в дополнительных полях.";

  const document = [
    "Адресат: " + recipient,
    "От: [ФИО заявителя]",
    cityLine,
    "Контакт для ответа: [указать удобный способ связи]",
    "",
    "ОБРАЩЕНИЕ",
    info.subject,
    "",
    "Суть обращения",
    narrativeBlock,
    timeLine,
    desiredLine,
    previousLine,
    evidenceLine,
    "",
    "В связи с изложенным прошу:",
    ...info.ask.map((item, index) => (index + 1) + ". " + item),
    "",
    "При наличии прошу учесть приложенные материалы, подтверждающие изложенные обстоятельства.",
    "Ответ прошу направить способом, указанным в контактных данных.",
    "",
    "Приложения: [перечислить документы, фотографии или иные материалы при наличии].",
    "",
    "Дата: [дата подачи]",
    "Подпись: [ФИО]"
  ].filter((line, index, list) => line !== "" || (index > 0 && list[index - 1] !== "")).join("\n");

  const review_notes = [];
  if (!cleanText(data.recipient)) review_notes.push("Уточните точное название организации или должность адресата.");
  if (!cleanText(data.city)) review_notes.push("При необходимости добавьте населённый пункт и точное место события.");
  if (!cleanText(data.since)) review_notes.push("Уточните дату или период, чтобы адресату было проще проверить обстоятельства.");
  if (!cleanText(data.evidence)) review_notes.push("Перечислите только реально имеющиеся доказательства и приложите копии при необходимости.");
  review_notes.push("Сверьте переформулированный текст с исходными фактами и исправьте неточности.");
  review_notes.push("Замените поля в квадратных скобках и проверьте документ перед отправкой.");

  return {
    document,
    plan: plans.map(([title, description]) => ({ title, description })),
    review_notes: review_notes.slice(0, 6)
  };
}

